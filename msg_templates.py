def get_template(speaker, situation, **kwargs):
    """
    テンプレートからランダムに1つ選んで返す
    
    Args:
        speaker: "pros" | "judge" | "def"
        situation: "opening" | "exchange" | "tired" など
        **kwargs: case="歯を磨いた" のように渡すと {case} を埋め込む
    
    Returns:
        セリフ文字列
    """
    import random
    
    templates = TEMPLATES.get(speaker, {}).get(situation, ["..."])
    line = random.choice(templates)
    
    if kwargs:
        line = line.format(**kwargs)
    
    return line